ACCOUNT = "synthetic-cross-source-account"
OTHER_PEER = "203.0.113.24"


@pytest.fixture
def source_snapshot():
    return {}


@pytest.fixture
def sources(scenario, tmp_path, monkeypatch, source_snapshot):
    """Change one association dimension in otherwise identical source records."""
    at = datetime.fromtimestamp(REALTIME_US / 1_000_000, timezone.utc)
    monkeypatch.setattr(ssh_module, "_now", lambda: at + timedelta(seconds=4000))
    monkeypatch.setattr(network_store, "_now_us", lambda: int(NOW * 1_000_000))
    net = NetworkStore(tmp_path / "network.sqlite")
    deliver(net, 1, [event(index) for index in range(10)])
    drain(net)
    anchor, = net.incidents()["items"]
    ssh = TelemetryStore(tmp_path / "ssh.sqlite")
    source = "auth-b" if scenario == "wrong_host" else "auth-a"
    peer = OTHER_PEER if scenario == "wrong_peer" else REMOTE
    offset = 3600 if scenario == "outside_window" else 0
    records = [
        {"event_id": f"cross-source-failure-{index}",
         "timestamp": (at + timedelta(seconds=20 + offset + index)).isoformat(),
         "identifier": "sshd",
         "message": f"Failed password for {ACCOUNT} from {peer} port 42000 ssh2"}
        for index in range(3)
    ]
    if scenario == "linked_success":
        records.append({
            "event_id": "cross-source-success",
            "timestamp": (at + timedelta(seconds=24)).isoformat(),
            "identifier": "sshd",
            "message": f"Accepted publickey for {ACCOUNT} from {peer} port 42000 ssh2",
        })
    ingested = ssh.ingest(source, "synthetic-cross-source.invalid", "cross-source-batch", records)
    assert ingested["accepted"] == len(records) and ingested["incident_ids"]
    # A negative must have actual retained SSH evidence which association excludes,
    # rather than pass merely because parsing/detection produced no SSH incident.
    with ssh._connection() as db:
        assert db.execute("SELECT count(*) FROM incident_evidence").fetchone()[0] == len(records)
    mapping = AssetMapping("cross-source-asset", ("auth-a",), (
        NetworkBinding(profile().source_id, (DESTINATION,), (profile().revision,)),
    ))
    source_snapshot.update({path: store_digest(path) for path in (net.path, ssh.path)})
    return net, ssh, mapping, anchor, at


def response_for(case, claim_mode):
    """Scripted claims cite only the dossier generated by the real preview."""
    network = [row for row in case["evidence"] if row["kind"] == "network_tcp"]
    ssh = [row for row in case["evidence"] if row["kind"] == "ssh"]
    if claim_mode == "network_only":
        claims = [{"kind": "multiple_destination_ports",
                   "evidence_ids": [row["event_id"] for row in network[:2]]}]
    elif claim_mode == "forced_association":
        # Known citations isolate unsupported association from unknown-ID rejection.
        claims = [{"kind": "ssh_network_associated",
                   "evidence_ids": [row["event_id"] for row in network[:2]]}]
    else:
        selected = next((row for row in ssh if row["event_type"] == "auth_success"), ssh[0])
        claims = [
            {"kind": "ssh_network_associated",
             "evidence_ids": [network[0]["event_id"], selected["event_id"]]},
            {"kind": "authentication_succeeded" if selected["event_type"] == "auth_success"
             else "ssh_failure_observed", "evidence_ids": [selected["event_id"]]},
        ]
    return json.dumps({
        "verdict": "escalate", "confidence": "medium", "revision": case["revision"],
        "rationale": "Authored integration probe; this is not a model prediction.",
        "evidence_ids": [], "attack_techniques": [], "claims": claims,
    })


@pytest.mark.parametrize("scenario,claim_mode,ssh_count,association,state,reason_codes", [
    ("linked_failure", "associated", 3, "linked", "complete", []),
    ("linked_success", "associated", 4, "linked", "complete", []),
    ("wrong_host", "forced_association", 0, "unmatched", "review", ["unsupported_claim"]),
    ("wrong_host", "network_only", 0, "unmatched", "complete", []),
    ("wrong_peer", "forced_association", 0, "unmatched", "review", ["unsupported_claim"]),
    ("wrong_peer", "network_only", 0, "unmatched", "complete", []),
    ("outside_window", "forced_association", 0, "unmatched", "review", ["unsupported_claim"]),
    ("outside_window", "network_only", 0, "unmatched", "complete", []),
], ids=[
    "mapped-failure-associated", "mapped-success-associated",
    "wrong-host-reject-association", "wrong-host-keep-network",
    "wrong-peer-reject-association", "wrong-peer-keep-network",
    "outside-window-reject-association", "outside-window-keep-network",
])
def test_source_evidence_through_manual_api_service(
    world, sources, source_snapshot, scenario, claim_mode, ssh_count, association,
    state, reason_codes,
):
    w = world
    preview = w.service.preview(w.case_id, 1)
    case = preview["case"]
    assert case["review_state"] == "current"
    assert case["association_state"] == association
    assert case["counts"] == {
        "network": {"observed": 10, "retained": 10, "included": 10},
        "ssh": {"observed": ssh_count, "retained": ssh_count, "included": ssh_count},
    }
    assert case["input_complete"] and case["timeline_complete"] and case["summary_complete"]
    assert case["coverage_complete"] is None
    assert "shared_ip_not_identity" in case["limitations"]
    references = preview["local_refs"]
    assert set(references) == {row["event_id"] for row in case["evidence"]}
    expected_ssh = {f"cross-source-failure-{index}" for index in range(3)} if ssh_count else set()
    if scenario == "linked_success":
        expected_ssh.add("cross-source-success")
    assert {(ref["source_id"], ref["event_id"]) for ref in references.values() if ref["kind"] == "ssh"} == {
        ("auth-a", identity) for identity in expected_ssh
    }
    assert {(ref["source_id"], ref["event_id"]) for ref in references.values() if ref["kind"] == "network"} == {
        (profile().source_id, event(index).event_id) for index in range(10)
    }
    assert all(row["account"] == w.ssh.aliases("U", ACCOUNT)
               for row in case["evidence"] if row["kind"] == "ssh")
    successes = [row for row in case["evidence"] if row.get("event_type") == "auth_success"]
    assert len(successes) == (1 if scenario == "linked_success" else 0)
    if successes:
        assert references[successes[0]["event_id"]]["event_id"] == "cross-source-success"

    response = response_for(case, claim_mode)
    w.response = httpx.Response(200, json=payload(w.ssh.profile, response))
    assert not w.service.run_once() and w.requests == []
    job = w.service.enqueue(w.case_id, 1, preview["preview_key"], "synthetic-operator")
    assert w.service.enqueue(w.case_id, 1, preview["preview_key"], "synthetic-operator")["id"] == job["id"]
    assert w.requests == []
    assert w.service.run_once()
    saved_job = w.service.job(job["id"])
    assert saved_job["state"] == state and not saved_job["stale"]
    result = saved_job["result"]
    assert result["verdict"] == ("abstain" if state == "review" else "escalate")
    validation = result["metadata"]["evidence_validation"]
    assert validation["status"] == ("requires_review" if reason_codes else "valid")
    assert [item["code"] for item in validation["reasons"]] == reason_codes
    assert validation["proposal"] == json.loads(response)
    assert validation["free_text_requires_review"] is True
    assert result["metadata"]["execution_mode"] == "api"
    assert result["metadata"]["offline"] is False
    assert result["usd"] == 0.00016

    assert len(w.requests) == 1
    request_text = w.requests[0].content.decode()
    assert json.loads(request_text) == joint_triage_api.request(w.ssh.profile, case)
    raw_values = {
        REMOTE, OTHER_PEER, DESTINATION, ACCOUNT, "auth-a", "auth-b", profile().source_id,
        "cross-source-asset", "synthetic-cross-source.invalid", "cross-source-batch",
        "cross-source-success", "synthetic-operator", sources[3]["incident_id"], w.case_id,
        str(w.settings.database_path), str(w.ssh.settings.keys_file), str(w.ssh.settings.profile_path),
        sources[4].isoformat(), profile().revision,
        *(str(path) for path in source_snapshot),
        *(f"cross-source-failure-{index}" for index in range(3)),
        *(event(index).event_id for index in range(10)),
    }
    assert all(value not in request_text for value in raw_values)
    assert not {"meta", "local_refs", "preview", "preview_key"}.intersection(case)
    assert len(rows(w.service.jobs, "ai_jobs")) == 1
    assert rows(w.service.jobs, "ai_calls") == []
    call, = rows(w.ssh.jobs, "ai_calls")
    assert call["charged"] == 160
    assert not {"total_limit", "daily_limit"}.intersection(
        row["name"] for row in rows(w.service.jobs, "ai_meta")
    )
    assert w.service.status()["budget"] == w.ssh.jobs.budget()
    assert w.ssh.jobs.budget()["charged_usd"] == 0.00016
    assert w.ssh.jobs.budget()["reserved_usd"] == 0
    assert not w.service.run_once()

    history = w.service.history(w.case_id)
    assert len(history) == 1 and history[0]["id"] == job["id"]
    restored = reopen(w)
    assert restored.history(w.case_id) == history
    assert restored.job(job["id"])["result"] == result
    assert restored.enqueue(w.case_id, 1, restored.preview(w.case_id, 1)["preview_key"],
                            "synthetic-operator")["id"] == job["id"]
    assert not restored.run_once()
    assert len(w.requests) == len(rows(w.ssh.jobs, "ai_calls")) == 1
    assert {path: store_digest(path) for path in source_snapshot} == source_snapshot
